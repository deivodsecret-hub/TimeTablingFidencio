const DAYS = ['Lunes', 'Martes', 'Miércoles', 'Jueves', 'Viernes'];

// Helper function to create availability from time ranges per day
// Time slots reference:
// 0: "07:00 - 07:55", 1: "07:55 - 08:50", 2: "08:50 - 09:45", 3: "09:45 - 10:40",
// 4: "10:40 - 11:10 (Receso)", 5: "11:10 - 12:05", 6: "12:05 - 13:00", 7: "13:00 - 13:55",
// 8: "13:55 - 14:00 (Receso)", 9: "14:00 - 14:55", 10: "14:55 - 15:50", 11: "15:50 - 16:45",
// 12: "16:45 - 17:40", 13: "17:40 - 18:00 (Receso)", 14: "18:00 - 18:55", 15: "18:55 - 19:50", 16: "19:50 - 20:45"

const createAvailability = (daySlots) => {
    const availability = {};
    DAYS.forEach(day => {
        availability[day] = {};
        const slots = daySlots[day] || [];
        slots.forEach(slotIndex => {
            if (TIME_SLOTS[slotIndex] && !TIME_SLOTS[slotIndex].includes('Receso')) {
                availability[day][TIME_SLOTS[slotIndex]] = true;
            }
        });
    });
    return availability;
};

